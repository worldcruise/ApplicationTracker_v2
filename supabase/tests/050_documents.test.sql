begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select no_plan();
select ok(not has_table_privilege('authenticated','public.document_blobs','SELECT'),'authenticated users cannot select raw blobs');
select ok(not has_table_privilege('authenticated','private.document_render_keys','SELECT'),'render secrets have no user SELECT grant');
select ok(not has_function_privilege('authenticated','public.configure_document_render_key(text,text)','EXECUTE'),'only an operator can register signing keys');
select ok(not has_function_privilege('authenticated','private.valid_render_signature(text,text,text)','EXECUTE'),'signature verifier is internal');
select ok(not (select rolbypassrls from pg_roles where rolname='app_document_exporter'),'export executor cannot bypass RLS');
select ok(not has_table_privilege('app_document_exporter','public.resume_versions','SELECT'),'export executor has no resume source privilege');
select ok(not has_table_privilege('app_document_exporter','public.candidate_profile_revisions','SELECT'),'export executor has no profile history privilege');
select ok((select relforcerowsecurity from pg_class where oid='public.documents'::regclass),'document metadata forces RLS');
select ok((select relforcerowsecurity from pg_class where oid='public.cover_letter_versions'::regclass),'letter versions force RLS');
select ok(not has_table_privilege('authenticated','public.cover_letter_versions','UPDATE'),'letter editing requires a new immutable version');
select ok(not has_table_privilege('authenticated','public.documents','INSERT'),'clients cannot insert self-attested PDF metadata');
select ok(has_function_privilege('authenticated','public.export_frozen_document(uuid,uuid)','EXECUTE'),'frozen export is a distinct protected command');
select set_config('request.jwt.claims','{"sub":"a8000000-0000-4000-9000-000000000001","role":"authenticated"}',true);
set local role authenticated;
select throws_ok($$select public.export_frozen_document(gen_random_uuid(),gen_random_uuid())$$,'42501','FORBIDDEN','unknown or unauthorized export reveals no existence');
select throws_ok($$select public.configure_document_render_key('test',repeat('0',64))$$,'42501',null,'user cannot configure a signing key');
reset role;
select * from finish();
rollback;
